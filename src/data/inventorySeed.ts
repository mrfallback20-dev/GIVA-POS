/**
 * The raw catalogue above was entered with ZAR (rand) cost/selling values in
 * `costPrice` / `sellingPrice`, while `sellingPriceUsd` holds the real USD price.
 * Everywhere else in the app `costPrice` / `sellingPrice` mean USD, so a product
 * with a R24 cost and an $8 price looked like it was sold at a loss.
 * Convert once here: USD cost = ZAR cost scaled by the USD/ZAR price ratio.
 */
export const INITIAL_PRODUCTS: Product[] = RAW_PRODUCTS.map((p) => {
  const ratio = p.sellingPrice > 0 ? p.sellingPriceUsd / p.sellingPrice : 1;
  const costUsd = Number((p.costPrice * ratio).toFixed(2));
  return {
    ...p,
    costPrice: costUsd,
    costPriceUsd: costUsd,
    sellingPrice: p.sellingPriceUsd,
    sellingPriceZig: Number((p.sellingPriceUsd * 40).toFixed(2)),
    lowStockThreshold: p.lowStockThreshold ?? 5,
  };
});
